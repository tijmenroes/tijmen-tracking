  id         bigint generated by default as identity primary key,
  name       text not null unique,
  created_by uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists board_members (
  board_id  bigint not null references boards (id) on delete cascade,
  user_id   uuid not null references auth.users (id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (board_id, user_id)
);

create table if not exists activity_events (
  id             bigint generated by default as identity primary key,
  board_id       bigint not null references boards (id) on delete cascade,
  actor_user_id  uuid not null references auth.users (id) on delete cascade,
  actor_nickname text not null,
  event_type     text not null check (event_type in ('workout_completed', 'weight_weekly')),
  workout_id     bigint references workouts (id) on delete cascade,
  weight_id      bigint references "Weight" (id) on delete set null,
  payload        jsonb not null default '{}'::jsonb,
  occurred_at    timestamptz not null default now(),
  created_at     timestamptz not null default now()
);

create index if not exists activity_events_board_occurred_idx
  on activity_events (board_id, occurred_at desc);
create unique index if not exists activity_events_one_workout_per_board
  on activity_events (board_id, workout_id) where workout_id is not null;
create unique index if not exists activity_events_one_weight_per_board
  on activity_events (board_id, weight_id) where weight_id is not null;

alter table boards enable row level security;
alter table board_members enable row level security;
alter table activity_events enable row level security;

create policy "Members can read their boards"
  on boards for select
  using (exists (
    select 1 from board_members
    where board_members.board_id = boards.id
      and board_members.user_id = auth.uid()
