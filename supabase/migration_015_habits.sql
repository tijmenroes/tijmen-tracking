-- Migration 015 – Habit tracker
-- Run in the Supabase SQL editor after migration_014.
--
-- Design notes (full spec: docs/habit-tracker.md):
-- * habit_logs is sparse: it only holds days the user explicitly set. A
--   missing row means "use the auto source, else the habit's default"
--   (unchecked for 'do', checked for 'avoid').
-- * Auto sources (saved workouts, Weight entries) are read at query time and
--   never copied in here, so editing a workout's date or deleting it is
--   reflected without any sync code.
-- * Child tables carry their own user_id plus a composite FK to
--   habits (id, user_id). RLS stays a plain equality, and the FK guarantees a
--   row can never point at another user's habit — also for writers that
--   bypass RLS (e.g. a future service-role backend).
-- * RLS uses (select auth.uid()) so Postgres evaluates it once per statement
--   instead of once per row.
-- * Upserts need both an insert AND an update policy (see migration 007).
-- * Safe to re-run: tables use "if not exists" and policies are recreated.
-- ============================================================

-- ------------------------------------------------------------
-- habits
-- kind: 'do' (check the days you did it), 'avoid' (days start checked;
-- uncheck the days it went wrong), 'weight' (weekly average weight change).
-- auto_source fills in 'do' days from other tables.
-- ------------------------------------------------------------
create table if not exists habits (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name        text not null check (char_length(btrim(name)) between 1 and 100),
  why         text check (char_length(why) <= 500),
  kind        text not null check (kind in ('do', 'avoid', 'weight')),
  auto_source text check (auto_source in ('workouts', 'weight')),
  start_date  date not null,
  sort_order  integer not null default 0,
  archived_at timestamptz,
  created_at  timestamptz not null default now(),
  -- Target of the composite foreign keys below.
  unique (id, user_id),
  check (auto_source is null or kind = 'do')
);

-- ------------------------------------------------------------
-- habit_targets
-- Target history: a change applies from its week onwards, older weeks keep
-- the target they had. 'do' = min days done, 'avoid' = max days missed,
-- 'weight' = max kg change per week (negative for a cut).
-- ------------------------------------------------------------
create table if not exists habit_targets (
  habit_id       bigint not null,
  user_id        uuid not null default auth.uid(),
  effective_from date not null check (extract(isodow from effective_from) = 1),
  target         numeric(5, 2) not null check (target between -10 and 10),
  primary key (habit_id, effective_from),
  foreign key (habit_id, user_id) references habits (id, user_id) on delete cascade
);

-- ------------------------------------------------------------
-- habit_logs
-- One explicit state per habit per day. For 'weight' habits a row on the
-- Monday is a manual override of that week's result.
-- ------------------------------------------------------------
create table if not exists habit_logs (
  habit_id bigint not null,
  user_id  uuid not null default auth.uid(),
  date     date not null,
  done     boolean not null,
  primary key (habit_id, date),
  foreign key (habit_id, user_id) references habits (id, user_id) on delete cascade
);

-- The week screen loads logs across all habits for a user and date range.
create index if not exists habit_logs_user_date_idx on habit_logs (user_id, date);

-- ------------------------------------------------------------
-- daily_checkins
-- Happiness (1–10) and a short journal per day; both optional.
-- ------------------------------------------------------------
create table if not exists daily_checkins (
  user_id   uuid not null default auth.uid() references auth.users (id) on delete cascade,
  date      date not null,
  happiness smallint check (happiness between 1 and 10),
  journal   text check (char_length(journal) <= 10000),
  primary key (user_id, date)
);

